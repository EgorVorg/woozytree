//! Действия с файлами пользователя: корзина, удаление, открытие и проводник.
//!
//! Модуль трогает реальные файлы, поэтому здесь особенно важно ничего не терять:
//! удаление в корзину идёт через системный API (`trash`), безвозвратное — только
//! по явному требованию (`permanent == true`), а ошибки по одному пути не
//! прерывают обработку остальных и возвращаются текстом для окна.

pub mod ops;

/// Временная папка для тестов действий с файлами.
///
/// Обычно это системный `%TEMP%`, но в ограниченной среде запись туда может быть
/// запрещена — тогда берём папку внутри `target`, который и так принадлежит
/// сборке. Тесты трогают только эту папку, а не данные пользователя.
#[cfg(test)]
pub(crate) fn test_dir() -> tempfile::TempDir {
    tempfile::tempdir().unwrap_or_else(|_| {
        let base = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("target")
            .join("test-tmp");
        std::fs::create_dir_all(&base).expect("не удалось создать папку для тестовых tempdir");
        tempfile::tempdir_in(base).expect("не удалось создать временную папку теста")
    })
}
